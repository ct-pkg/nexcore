#!/usr/bin/env python3
"""abi-layout — 用真实编译器实测发布头的 ABI 布局，并与仓库 golden 比对。

为什么不用文档里的数字：ACC-A-10 的基线必须是**实测导出**。本工具的做法是
解析已生成的 `build/abi/NexCore.h`（只解析声明与字段名，不解析任何尺寸），
再生成一段 C 探针，用 cc 编译运行，把 `sizeof` / `__alignof__` / `offsetof`
的真实结果打印出来。golden 只能由 `--write` 产出，`--check` 只做二值比对。

字段声明顺序单独输出一行（order=...）：同一宽度的两个字段互换位置时
offset 与 size 都不变，只有顺序行能拦住（ACC-A-04 的“重排”负例靠它）。

用法：
  python3 tools/abi_layout.py --header build/abi/NexCore.h --check
  python3 tools/abi_layout.py --header build/abi/NexCore.h --write
  python3 tools/abi_layout.py --header <被改坏的头> --check   # 期望 rc=2
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

FORMAT_VERSION = "abi-layout v1"
ENUM_RE = re.compile(r"\benum\s+([A-Za-z_]\w*)\s*\{(.*?)\}\s*;", re.DOTALL)
STRUCT_RE = re.compile(r"\bstruct\s+([A-Za-z_]\w*)\s*\{(.*?)\}\s*;", re.DOTALL)
TYPEDEF_RE = re.compile(r"\btypedef\s+([^;]+?)\s*;")
ID_RE = re.compile(r"^[A-Za-z_]\w*$")


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def split_top_level(text: str, sep: str) -> list[str]:
    """按 depth==0 的分隔符切分（enum 成员里的 offsetof(...) 含逗号）。"""
    parts: list[str] = []
    depth = 0
    current: list[str] = []
    for ch in text:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append("".join(current))
            current = []
            continue
        current.append(ch)
    parts.append("".join(current))
    return parts


def parse_fields(body: str) -> list[tuple[str, str]]:
    """返回 [(声明类型, 字段名)]，保持声明顺序；函数指针字段也支持。"""
    fields: list[tuple[str, str]] = []
    for decl in body.split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        m = re.match(r"^(.*?)\(\s*\*\s*([A-Za-z_]\w*)\s*\)\s*\((.*)\)$", decl)
        if m:
            ret = m.group(1).strip()
            name = m.group(2)
            params = " ".join(m.group(3).split())
            fields.append((f"{ret} (*)({params})", name))
            continue
        m = re.match(r"^(.+?)\s+([A-Za-z_]\w*)$", decl)
        if not m:
            raise SystemExit(f"abi-layout: 无法解析字段声明: {decl!r}")
        fields.append((m.group(1).strip(), m.group(2)))
    return fields


def parse_header(path: Path) -> tuple[list[tuple[str, list[str]]], list[tuple[str, list[tuple[str, str]]]]]:
    text = strip_comments(path.read_text(encoding="utf-8"))

    enums: list[tuple[str, list[str]]] = []
    for name, body in ENUM_RE.findall(text):
        members = []
        for item in split_top_level(body, ","):
            item = item.strip()
            if not item:
                continue
            identifier = item.split("=", 1)[0].strip()
            if not ID_RE.match(identifier):
                raise SystemExit(f"abi-layout: enum {name} 无法解析成员: {item!r}")
            members.append(identifier)
        enums.append((name, members))

    # typedef 名：函数指针取 `(*NAME)` 里的名字，其余取 `;` 前最后一个标识符。
    typedefs = []
    for decl in TYPEDEF_RE.findall(text):
        decl = " ".join(decl.split())
        if "struct" in decl.split():
            continue
        fn = re.search(r"\(\s*\*\s*([A-Za-z_]\w*)\s*\)", decl)
        name = fn.group(1) if fn else re.search(r"([A-Za-z_]\w*)\s*$", decl).group(1)
        if ID_RE.match(name) and name not in typedefs:
            typedefs.append(name)

    structs: list[tuple[str, list[tuple[str, str]]]] = []
    for name, body in STRUCT_RE.findall(text):
        structs.append((name, parse_fields(body)))

    if not structs:
        raise SystemExit(f"abi-layout: {path} 中没有 struct 定义")
    return enums, typedefs, structs


def emit_probe(enums, typedefs, structs) -> str:
    lines = [
        "/* GENERATED by tools/abi_layout.py -- 探针，不写回仓库。 */",
        '#include <stdio.h>',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '#include "NexCore.h"',
        "",
        "int main(void)",
        "{",
    ]
    for enum_name, members in enums:
        lines.append(f'    printf("[enum {enum_name}]\\n");')
        for member in members:
            lines.append(
                f'    printf("  {member} = %lld\\n", (long long)({member}));'
            )
    for name in typedefs:
        lines.append(
            f'    printf("[typedef {name}] size=%zu align=%zu\\n",'
            f' sizeof({name}), (size_t)__alignof__({name}));'
        )
    for struct_name, fields in structs:
        lines.append(
            f'    printf("[struct {struct_name}] size=%zu align=%zu\\n",'
            f' sizeof(struct {struct_name}), (size_t)__alignof__(struct {struct_name}));'
        )
        order = ",".join(name for _, name in fields)
        lines.append(f'    printf("  order={order}\\n");')
        for decl_type, name in fields:
            lines.append(
                f'    printf("  {name} type={decl_type} offset=%zu size=%zu\\n",'
                f' offsetof(struct {struct_name}, {name}),'
                f' sizeof(((struct {struct_name} *)0)->{name}));'
            )
    lines += ["    return 0;", "}", ""]
    return "\n".join(lines)


def measure(header: Path, cc: str) -> str:
    enums, typedefs, structs = parse_header(header)
    with tempfile.TemporaryDirectory(prefix="nxabi.") as tmp:
        tmpdir = Path(tmp)
        (tmpdir / "probe.c").write_text(emit_probe(enums, typedefs, structs), encoding="utf-8")
        exe = tmpdir / "probe"
        cmd = [
            cc,
            "-std=c99",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-I",
            str(header.parent.resolve()),
            str(tmpdir / "probe.c"),
            "-o",
            str(exe),
        ]
        built = subprocess.run(cmd, capture_output=True, text=True)
        if built.returncode != 0:
            print(built.stdout, end="", file=sys.stderr)
            print(built.stderr, end="", file=sys.stderr)
            raise SystemExit(f"abi-layout: 探针编译失败（header={header}）")
        ran = subprocess.run([str(exe)], capture_output=True, text=True)
        if ran.returncode != 0:
            raise SystemExit(f"abi-layout: 探针运行失败 rc={ran.returncode}")
        body = ran.stdout
    head = (
        f"# {FORMAT_VERSION} —— 由 tools/abi_layout.py 用 {cc} 实测发布头生成，不要手改\n"
        f"# 值来自 sizeof/__alignof__/offsetof；type= 是头里的声明，用于人工核对\n"
    )
    return head + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--header", default="build/abi/NexCore.h")
    ap.add_argument("--golden", default="abi/abi-layout.txt")
    ap.add_argument("--emit", default=None, help="把实测结果另存一份（如 build/abi/abi-layout.txt）")
    ap.add_argument("--cc", default="cc")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="与 golden 逐行比对；漂移 rc=2")
    mode.add_argument("--write", action="store_true", help="把实测结果写入 golden")
    args = ap.parse_args()

    header = Path(args.header)
    if not header.is_file():
        print(f"abi-layout: 头文件不存在: {header}", file=sys.stderr)
        return 1

    actual = measure(header, args.cc)
    if args.emit:
        emit = Path(args.emit)
        emit.parent.mkdir(parents=True, exist_ok=True)
        emit.write_text(actual, encoding="utf-8")
    golden = Path(args.golden)

    if args.write:
        golden.parent.mkdir(parents=True, exist_ok=True)
        golden.write_text(actual, encoding="utf-8")
        print(f"wrote {golden} ({len(actual.splitlines())} lines)")
        return 0

    if not golden.is_file():
        print(f"abi-layout: 缺 golden {golden}（先人工核对 --write 的结果再入库）", file=sys.stderr)
        return 1

    want = golden.read_text(encoding="utf-8")
    if want == actual:
        print(f"abi-layout: PASS（实测 == {golden}，{len(actual.splitlines())} 行）")
        return 0

    with tempfile.TemporaryDirectory(prefix="nxabi.diff.") as tmp:
        tmpdir = Path(tmp)
        (tmpdir / "golden").write_text(want, encoding="utf-8")
        (tmpdir / "actual").write_text(actual, encoding="utf-8")
        diff = subprocess.run(
            ["diff", "-u", str(tmpdir / "golden"), str(tmpdir / "actual")],
            capture_output=True,
            text=True,
        )
    print(diff.stdout, end="", file=sys.stderr)
    print(
        f"abi-layout: FAIL 实测布局与 {golden} 不一致（改字段必须升 NEXCORE_ABI_VERSION，"
        f"并重新生成 golden）",
        file=sys.stderr,
    )
    return 2


if __name__ == "__main__":
    sys.exit(main())
