#!/usr/bin/env python3
"""schema-hash — 把 Schema 的 sha256 做成三方一致、可二值判定的门禁。

三方：
  1. tests/fixture.schema.yaml 的真实字节（唯一来源）
  2. abi/schema-hash.txt（入库 golden，供人工核对）
  3. src/NexCore.ct 的编译期常量 NEXCORE_SCHEMA_HASH（运行时 create 用它判断）
  （schema/generated/** 的文件头由 nexcore_schema_gen.py --check 覆盖）

用法：
  python3 tools/schema_hash.py --check
  python3 tools/schema_hash.py --write          # 人工确认后更新 golden
  python3 tools/schema_hash.py --emit-header build/abi/schema_hash_test.h
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

HEX64_RE = re.compile(r"^[0-9a-f]{64}$")
C_LITERAL_RE = re.compile(r'#define\s+NEXCORE_SCHEMA_HASH\s+"([0-9a-f]{64})"')


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--schema", default="tests/fixture.schema.yaml")
    ap.add_argument("--golden", default="abi/schema-hash.txt")
    ap.add_argument("--c-source", default="src/NexCore.ct")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--emit-header", default=None, metavar="PATH")
    args = ap.parse_args()

    schema = Path(args.schema)
    if not schema.is_file():
        print(f"schema-hash: 缺 Schema 源 {schema}", file=sys.stderr)
        return 1
    actual = sha256_of(schema)

    if args.emit_header:
        out = Path(args.emit_header)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            "/* GENERATED by tools/schema_hash.py -- 供测试使用，不写回仓库。 */\n"
            f'#define NEXCORE_TEST_SCHEMA_HASH "{actual}"\n',
            encoding="utf-8",
        )
        print(f"wrote {out} ({actual[:12]}…)")
        return 0

    golden = Path(args.golden)
    if args.write:
        golden.parent.mkdir(parents=True, exist_ok=True)
        golden.write_text(actual + "\n", encoding="utf-8")
        print(f"wrote {golden} ({actual})")
        print("注意：还要同步 src/NexCore.ct 的 NEXCORE_SCHEMA_HASH 与生成物", file=sys.stderr)
        return 0

    failures: list[str] = []
    if not golden.is_file():
        failures.append(f"缺 golden {golden}")
    else:
        stored = golden.read_text(encoding="utf-8").strip()
        if not HEX64_RE.match(stored):
            failures.append(f"{golden} 不是单个 64 位十六进制: {stored!r}")
        elif stored != actual:
            failures.append(f"{golden} 与 Schema 实测 hash 不等（golden={stored} actual={actual}）")

    c_source = Path(args.c_source)
    if not c_source.is_file():
        failures.append(f"缺 {c_source}")
    else:
        m = C_LITERAL_RE.search(c_source.read_text(encoding="utf-8"))
        if not m:
            failures.append(f"{c_source} 里找不到 #define NEXCORE_SCHEMA_HASH \"<64hex>\"")
        elif m.group(1) != actual:
            failures.append(
                f"{c_source} 的 NEXCORE_SCHEMA_HASH={m.group(1)} 与 Schema 实测 {actual} 不等"
            )

    if failures:
        for item in failures:
            print(f"schema-hash: FAIL {item}", file=sys.stderr)
        return 2

    print(f"schema-hash: PASS（Schema/golden/C 常量三方一致 {actual[:12]}…）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
